// Сравнение версий вида 1.7.0. Возвращает >0, если a новее b.
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map((n) => parseInt(n, 10) || 0);
  const pb = b.split('.').map((n) => parseInt(n, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

// Записи, которые пользователь ещё не видел: всё, что новее последней показанной
// версии. Если человек пропустил несколько обновлений — покажем их все разом.
export function entriesSince(lastSeen: string | null, current: string): ChangelogEntry[] {
  const upToCurrent = CHANGELOG.filter((e) => compareVersions(e.version, current) <= 0);
  if (!lastSeen) {
    // Первый запуск после появления этого окна: показываем только текущий релиз,
    // иначе новичок получил бы простыню из всей истории.
    return upToCurrent.slice(0, 1);
  }
  return upToCurrent.filter((e) => compareVersions(e.version, lastSeen) > 0);
}
